import { RoleDefinition } from './agent_types.js';

/** Marks files HexaCore generated, so a later export knows it may replace them. */
export const GENERATED_MARK = '<!-- generated by HexaCore: hexacore agents export -->';

/**
 * Renders a Claude Code subagent file. MCP tools are named mcp__<server>__<tool>, where <server> is
 * the name HexaCore was registered under in the client (`claude mcp add <server> ...`).
 */
export function renderAgentFile(def: RoleDefinition, serverName: string): string {
  const tools = [...def.clientTools, ...def.hexacoreTools.map((t) => `mcp__${serverName}__${t}`)];
  return [
    '---',
    `name: ${def.name}`,
    `description: ${def.description}`,
    `tools: ${tools.join(', ')}`,
    '---',
    '',
    GENERATED_MARK,
    '',
    def.instructions.trim(),
    '',
  ].join('\n');
}

/** MCP server names are used inside tool names; keep them to what clients accept. */
export function isValidServerName(name: string): boolean {
  return /^[A-Za-z0-9_-]{1,64}$/.test(name);
}
